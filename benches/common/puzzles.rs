use sudoku_engine::board::Board;

fn board_from_string(puzzle: &str) -> Board {
    assert_eq!(puzzle.len(), 81);

    let mut board = Board::empty();

    for (index, byte) in puzzle.bytes().enumerate() {
        let value = byte - b'0';

        if value != 0 {
            let row = index / 9;
            let col = index % 9;

            board.set(row, col, value as u8);
        }
    }

    board
}

